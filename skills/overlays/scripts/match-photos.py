#!/usr/bin/env python3
"""Scans <rush_dir>/Illustrations/ and produces a <rush>_photos-script.json template.

Expected naming convention (produced by source-illustrations.py):
    NN-category-photographer-name-subject.ext   (category optional)
    e.g. 01-pioneers-louis-daguerre-portrait.jpg

If <rush>_transcription.json exists, pre-fills the timecodes by looking for the photographer's
name in the transcript (fuzzy: Whisper mangles rare proper names:
Sischy -> "Sichi", Iturbide -> "Iturbid"...). The photos of one NN group are
spread from the timecode found (one photo every `--gap` seconds).

Claude (or the user) then validates/adjusts `timecode`, `durationSec`, `note`.

Usage:
    python3 match-photos.py /path/rush.mp4
    python3 match-photos.py /path/rush.mp4 --force            # overwrites the template
    python3 match-photos.py /path/rush.mp4 --gap 6 --duration 4
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

IMAGE_EXTS = {".jpg", ".jpeg", ".png", ".webp", ".gif", ".tif", ".tiff"}


def norm(s: str) -> str:
    s = unicodedata.normalize("NFKD", s).encode("ascii", "ignore").decode("ascii")
    return re.sub(r"[^a-z0-9 ]", " ", s.lower()).strip()


def parse_photo_filename(name: str) -> dict | None:
    """01-pioneers-louis-daguerre-boulevard-du-temple.jpg ->
    {id: "01", rest: "pioneers-louis-daguerre-boulevard-du-temple"}"""
    stem = Path(name).stem
    m = re.match(r"^(\d{1,3})-(.+)$", stem)
    if not m:
        return None
    return {"id": m.group(1), "rest": m.group(2)}


def find_name_in_transcript(words: list[dict], query: str, threshold: float = 0.72) -> float | None:
    """Looks for `query` (1-3 words) in the transcript with a fuzzy sliding window.
    Returns the start of the first match, or None."""
    q = norm(query)
    q_len = len(q.split())
    if not q or not words:
        return None
    best = (0.0, None)
    for i in range(len(words)):
        window = " ".join(norm(w["word"]) for w in words[i:i + q_len]).strip()
        if not window:
            continue
        ratio = difflib.SequenceMatcher(None, q, window).ratio()
        if ratio > best[0]:
            best = (ratio, words[i]["start"])
        if ratio >= 0.95:  # near-exact match, no need to go on
            break
    return best[1] if best[0] >= threshold else None


def sec_to_tc(seconds: float) -> str:
    m = int(seconds // 60)
    s = int(seconds % 60)
    return f"{m:02d}:{s:02d}"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("rush", help="Path to the rush video (Illustrations/ is looked for next to it)")
    parser.add_argument("--force", action="store_true", help="Overwrite an existing photos-script")
    parser.add_argument("--photos-dir", help="Override the folder (default: <rush_dir>/Illustrations)")
    parser.add_argument("--duration", type=float, default=4.0,
                        help="Default duration of a photo in seconds (default 4)")
    parser.add_argument("--gap", type=float, default=6.0,
                        help="Gap in seconds between photos of the same group (default 6)")
    args = parser.parse_args()

    rush = Path(args.rush).resolve()
    if not rush.exists():
        print(f"ERROR: rush not found: {rush}", file=sys.stderr)
        sys.exit(1)

    photos_dir = Path(args.photos_dir).resolve() if args.photos_dir else rush.parent / "Illustrations"
    if not photos_dir.exists():
        print(f"ERROR: folder not found: {photos_dir}", file=sys.stderr)
        print("  Tip: put the images in 'Illustrations/' next to the rush "
              "(generated by source-illustrations.py), or use --photos-dir.", file=sys.stderr)
        sys.exit(1)

    out_json = rush.with_name(rush.stem + "_photos-script.json")
    if out_json.exists() and not args.force:
        print(f"ERROR: {out_json.name} already exists. Use --force to overwrite.", file=sys.stderr)
        sys.exit(1)

    # Optional transcript to pre-fill the timecodes
    words = []
    transcript_path = rush.with_name(rush.stem + "_transcription.json")
    if transcript_path.exists():
        words = json.loads(transcript_path.read_text()).get("words", [])
        print(f"Transcript: {transcript_path.name} ({len(words)} words): timecodes pre-filled")
    else:
        print("No transcript: timecodes left at '??'")

    # Scan + group by numeric prefix
    groups: dict[str, list[dict]] = defaultdict(list)
    skipped: list[str] = []
    for f in sorted(photos_dir.iterdir()):
        if not f.is_file() or f.suffix.lower() not in IMAGE_EXTS:
            continue
        parsed = parse_photo_filename(f.name)
        if not parsed:
            skipped.append(f.name)
            continue
        groups[parsed["id"]].append({"file": f.name, "rest": parsed["rest"]})

    if not groups:
        print(f"ERROR: no image in the NN-name-subject.ext format in {photos_dir}", file=sys.stderr)
        sys.exit(1)

    photos_template = []
    for gid in sorted(groups.keys(), key=int):
        items = groups[gid]
        # The photographer's name = tokens common to the files of the group (without category)
        rests = [i["rest"] for i in items]
        common = rests[0].split("-")
        for r in rests[1:]:
            toks = r.split("-")
            common = [t for t in common if t in toks]
        name_guess = " ".join(t for t in common if t not in ("surcote", "souscote", "portrait"))

        base_tc = None
        if words and name_guess:
            base_tc = find_name_in_transcript(words, name_guess)
            status = f"-> found @ {sec_to_tc(base_tc)}" if base_tc is not None else "-> not found (??)"
            print(f"  #{gid} '{name_guess}' {status}")

        for k, item in enumerate(items):
            tc = "??"
            if base_tc is not None:
                tc = sec_to_tc(base_tc + k * args.gap)
            photos_template.append({
                "id": gid,
                "file": item["file"],
                "keywords": item["rest"].replace("-", " "),
                "timecode": tc,
                "durationSec": args.duration,
                "enabled": True,
                "note": "",
            })

    output = {
        "version": 1,
        "fps": 60,
        "rush": rush.name,
        "photos_dir": str(photos_dir),
        "defaults": {"durationSec": args.duration},
        "photos": photos_template,
    }
    out_json.write_text(json.dumps(output, indent=2, ensure_ascii=False))

    n_tc = sum(1 for p in photos_template if p["timecode"] != "??")
    print(f"\n✅ Template written: {out_json}")
    print(f"   {len(photos_template)} photos, {n_tc} timecodes pre-filled (CHECK them against the transcript).")
    if skipped:
        print(f"   ⚠️  {len(skipped)} files ignored (do not follow NN-name-subject.ext):")
        for s in skipped[:5]:
            print(f"      - {s}")
    print()
    print("Next step: check/adjust `timecode` and `durationSec`, set `enabled: false`")
    print("for the photos to discard, then run `render-segments.py` -> photos on V3 (priority over the V2 b-rolls).")


if __name__ == "__main__":
    main()
